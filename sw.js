/*
 * Service worker for the home-screen app. The tool's own files are fetched
 * from the network first, so every open gets the latest version; the cached
 * copy is only a fallback when offline. Sleeper/ESPN data is never cached here.
 */
var CACHE = 'hoops-v1';

self.addEventListener('install', function () { self.skipWaiting(); });
self.addEventListener('activate', function (e) { e.waitUntil(self.clients.claim()); });

self.addEventListener('fetch', function (e) {
  var req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== self.location.origin) return;
  e.respondWith(fetch(req, { cache: 'no-cache' }).then(function (res) {
    if (res.ok) {
      var copy = res.clone();
      caches.open(CACHE).then(function (c) { c.put(req, copy); });
    }
    return res;
  }).catch(function () {
    return caches.match(req);
  }));
});
